#!/usr/bin/env python3
"""compare.py - Module 4: comparison report data.

Runs the SAME processes through all six scheduling algorithms and prints the
average waiting / turnaround times, then shows one safe and one unsafe deadlock
example.  Every number comes from this program's own simulators.

    python3 compare.py                      print everything
    python3 compare.py --write report/results.md   also save as Markdown
    python3 compare.py --quantum 2          use a different Round-Robin quantum
"""
import os
import sys

import deadlock as D
import scheduler as S

HERE = os.path.dirname(os.path.abspath(__file__))
WORKLOADS = [
    ('A: staggered arrivals (4 processes)', 'processes.txt'),
    ('B: all arrive at time 0 (5 processes)', 'processes_all0.txt'),
    ('C: mixed workload with one long job (8 processes)', 'processes_mixed.txt'),
    ('D: CPU idle gap (3 processes)', 'processes_gap.txt'),
]


def md_table(results):
    lines = ['| Algorithm | Avg Waiting | Avg Turnaround | Max Waiting | Context Switches |',
             '|---|---|---|---|---|']
    for r in results:
        lines.append(f'| {r["label"]} | {r["avg_wait"]:.2f} | {r["avg_turn"]:.2f} | '
                     f'{r["max_wait"]} | {r["switches"]} |')
    return '\n'.join(lines)


def main(argv):
    quantum, write = None, None
    if '--quantum' in argv:
        quantum = int(argv[argv.index('--quantum') + 1])
    if '--write' in argv:
        write = argv[argv.index('--write') + 1]
    out = ['# MiniShell results (generated by compare.py)', '']
    totals = {k: [0.0, 0.0] for k in S.ALGOS}
    for title, fname in WORKLOADS:
        procs = S.load(os.path.join(HERE, 'samples', fname))
        results = S.compare(procs, quantum)
        out += [f'## Workload {title}', f'File: `samples/{fname}`', '']
        out += ['| PID | Arrival | Burst | Priority |', '|---|---|---|---|']
        out += [f'| {p.pid} | {p.arrival} | {p.burst} | {p.priority} |' for p in procs]
        out += ['', md_table(results), '']
        for r in results:
            totals[r['key']][0] += r['avg_wait']
            totals[r['key']][1] += r['avg_turn']
    k = len(WORKLOADS)
    out += [f'## Average over all {k} workloads', '',
            '| Algorithm | Mean Avg Waiting | Mean Avg Turnaround |', '|---|---|---|']
    for key, (w, t) in sorted(totals.items(), key=lambda kv: kv[1][0]):
        out.append(f'| {S.ALGOS[key][0]} | {w / k:.2f} | {t / k:.2f} |')
    out.append('')
    for title, fname in (('Safe example', 'system_safe.txt'), ('Unsafe example', 'system_unsafe.txt')):
        with open(os.path.join(HERE, 'samples', fname)) as fh:
            s = D.parse_system(fh.read())
        out += [f'## Deadlock - {title} (`samples/{fname}`)', '', '```']
        out.append(D.banker_report(s)[0].rstrip())
        if fname == 'system_unsafe.txt':
            out.append('')
            out.append(D.detect_report(s)[0].rstrip())
        out += ['```', '']
    text = '\n'.join(out) + '\n'
    print(text)
    if write:
        with open(write, 'w') as fh:
            fh.write(text)
        print(f'(saved to {write})')


if __name__ == '__main__':
    main(sys.argv[1:])
